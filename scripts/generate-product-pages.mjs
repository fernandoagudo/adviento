function replaceBlock(contents, startMarker, endMarker, replacement, label) {
  const startCount = contents.split(startMarker).length - 1;
  const endCount = contents.split(endMarker).length - 1;
  const start = contents.indexOf(startMarker);
  const end = contents.indexOf(endMarker);
  if (startCount !== endCount || startCount > 1 || (startCount && end < start)) throw new Error(`${label} has malformed generated markers.`);
  return startCount ? `${contents.slice(0, start + startMarker.length)}\n${replacement}\n${contents.slice(end)}` : null;
}

function renderCard(product) {
  const name = escapeHtml(product.title || product.name);
  const category = escapeHtml(product.categoryLabel || product.category);
  const subtitle = escapeHtml(product.subtitle || product.description || '');
  const image = product.imageUrl
    ? `<img src="${escapeHtml(product.imageUrl)}" alt="${name}" loading="lazy">`
    : '<span class="product-illustration" aria-hidden="true">✦</span>';
  const imageClass = escapeHtml(product.imageClass || 'product-image-one');
  const url = productUrl(product);
  const price = escapeHtml(displayPrice(product));
  return `      <article class="product-card"><a class="product-image ${imageClass}" href="${url}">${image}</a><div class="product-info"><p class="product-category">${category}</p><h3><a href="${url}">${name}</a></h3><p class="product-meta">${subtitle}</p><div class="product-bottom"><strong>${price}</strong><a href="${url}" aria-label="Ver ${name}">Ver más <span aria-hidden="true">↗</span></a></div></div></article>`;
}

function updateHomepage(homepage, products) {
  const cards = products.map(renderCard).join('\n');
  const marked = replaceBlock(homepage, homepageStart, homepageEnd, cards, 'index.html');
  if (marked !== null) return marked;
  const grid = '<div class="product-grid">';
  const gridStart = homepage.indexOf(grid);
  const legacy = homepage.indexOf('<!-- SUSTITUIR:', gridStart);
  const affiliate = homepage.indexOf('<p class="affiliate-note">', gridStart);
  const closing = homepage.lastIndexOf('</div>', affiliate);
  if (gridStart < 0 || legacy < gridStart || affiliate < 0 || closing < legacy) {
    throw new Error('index.html is missing its expected featured product grid.');
  }
  const contentStart = gridStart + grid.length;
  return `${homepage.slice(0, contentStart)}\n      ${homepageStart}\n${cards}\n      ${homepageEnd}\n      ${homepage.slice(closing)}`;
}

function updateSitemap(sitemap, products) {
  const marked = replaceBlock(sitemap, sitemapStart, sitemapEnd, '', 'sitemap.xml');
  let contents = marked ? marked.replace(sitemapStart, '').replace(sitemapEnd, '') : sitemap;
  const withoutComments = contents.replace(/<!--([\s\S]*?)-->/g, '').replace(/<\?xml\s+[^?]*\?>/gi, '');
  const tags = /<\/?([A-Za-z_][\w:.-]*)(?:\s[^<>]*?)?\s*\/?>/g;
  const stack = [];
  let match;
  while ((match = tags.exec(withoutComments))) {
    if (match[0].startsWith('</')) {
      if (stack.pop() !== match[1]) throw new Error('sitemap.xml has mismatched XML tags.');
    } else if (!match[0].endsWith('/>')) stack.push(match[1]);
  }
  if (stack.length || withoutComments.replace(tags, '').includes('<')) throw new Error('sitemap.xml has malformed XML markup.');
  const opens = [...contents.matchAll(/<urlset\b[^>]*>/g)];
  const closes = [...contents.matchAll(/<\/urlset\s*>/g)];
  if (opens.length !== 1 || closes.length !== 1 || closes[0].index < opens[0].index || contents.slice(closes[0].index + closes[0][0].length).trim()) {
    throw new Error('sitemap.xml must contain one well-formed urlset root.');
  }
  const entries = [...contents.matchAll(/<url\b[^>]*>[\s\S]*?<\/url\s*>/g)];
  if (entries.length !== [...contents.matchAll(/<url\b[^>]*>/g)].length || entries.length !== [...contents.matchAll(/<\/url\s*>/g)].length) {
    throw new Error('sitemap.xml contains an incomplete url entry.');
  }
  for (const entry of entries) {
    const locs = [...entry[0].matchAll(/<loc\b[^>]*>([\s\S]*?)<\/loc\s*>/g)];
    if (locs.length !== 1) throw new Error('sitemap.xml url entries must have one loc element.');
    if (/^https:\/\/adviento\.es\/productos(?:\/|$)/.test(locs[0][1].trim())) {
      const escapedEntry = entry[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      contents = contents.replace(new RegExp(`^[ \\t]*${escapedEntry}[ \\t]*\\r?\\n?`, 'm'), '');
    }
  }
  contents = contents.replace(/^[ \\t]+$/gm, '');
  contents = contents.replace(/\n{2,}/g, '\n');
  const urls = products.map((product) => {
    const url = `https://adviento.es${productUrl(product)}`.replaceAll('&', '&amp;');
    return `  <url><loc>${url}</loc></url>`;
  });
  const block = `  ${sitemapStart}\n${urls.join('\n')}\n  ${sitemapEnd}\n`;
  const rootClose = contents.match(/<\/urlset\s*>/);
  return `${contents.slice(0, rootClose.index)}${block}${contents.slice(rootClose.index)}`;
}

let products;
try {
  products = JSON.parse(await readFile(catalogPath, 'utf8'));
} catch (error) {
  throw new Error(`Could not read data/products.json: ${error.message}`);
}
const slugs = validateProducts(products);
const [homepage, sitemap] = await Promise.all([readFile(homepagePath, 'utf8'), readFile(sitemapPath, 'utf8')]);
const nextHomepage = updateHomepage(homepage, products);
const nextSitemap = updateSitemap(sitemap, products);

await mkdir(productsDirectory, { recursive: true });
let generatedPages = 0;
for (const product of products) {
  if (!product.slug) continue;
  const directory = join(productsDirectory, product.slug);
  await mkdir(directory, { recursive: true });
  await writeFile(join(directory, 'index.html'), renderStaticPage(product), 'utf8');
  generatedPages += 1;
}

let removedDirectories = 0;
for (const entry of await readdir(productsDirectory, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name === 'amazon' || slugs.has(entry.name)) continue;
  const directory = join(productsDirectory, entry.name);
  try {
    await readFile(join(directory, 'index.html'), 'utf8');
  } catch {
    continue;
  }
  await rm(directory, { recursive: true, force: true });
  removedDirectories += 1;
}

await Promise.all([
  writeFile(homepagePath, nextHomepage, 'utf8'),
  writeFile(sitemapPath, nextSitemap, 'utf8'),
]);
console.log(`Generated ${generatedPages} static product pages, removed ${removedDirectories} stale product directories, and synchronized ${products.length} homepage and sitemap entries.`);
