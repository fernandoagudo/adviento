#!/usr/bin/env node

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = resolve(projectDirectory, 'data/products.json');
const productsDirectory = resolve(projectDirectory, 'productos');
const homepagePath = resolve(projectDirectory, 'index.html');
const sitemapPath = resolve(projectDirectory, 'sitemap.xml');
const homepageStart = '<!-- Generated product cards:START -->';
const homepageEnd = '<!-- Generated product cards:END -->';
const sitemapStart = '<!-- Generated product URLs:START -->';
const sitemapEnd = '<!-- Generated product URLs:END -->';
const pageMarker = '<!-- Generated by scripts/generate-product-pages.mjs. -->';

function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function safeJson(value) {
  return JSON.stringify(value)
    .replaceAll('<', '\\u003c')
    .replaceAll('>', '\\u003e')
    .replaceAll('&', '\\u0026')
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029');
}

function validateProducts(products) {
  if (!Array.isArray(products)) throw new Error('data/products.json must contain an array.');
  const ids = new Set();
  const slugs = new Set();

  for (const [index, product] of products.entries()) {
    const label = `Product ${index + 1}`;
    if (!product || typeof product !== 'object' || Array.isArray(product)) throw new Error(`${label} must be an object.`);
    for (const field of ['id', 'type', 'category', 'affiliateUrl']) {
      if (typeof product[field] !== 'string' || !product[field].trim()) throw new Error(`${label} requires ${field}.`);
    }
    if (typeof (product.title || product.name) !== 'string' || !(product.title || product.name).trim()) {
      throw new Error(`${label} requires a title or name.`);
    }
    if (!Number.isFinite(product.price) || product.price < 0) throw new Error(`${label} has an invalid price.`);
    if (!/^https:\/\//i.test(product.affiliateUrl)) throw new Error(`${label} affiliateUrl must use HTTPS.`);
    if (ids.has(product.id)) throw new Error(`Duplicate product id: ${product.id}.`);
    ids.add(product.id);

    if (product.slug !== undefined && product.slug !== '') {
      if (typeof product.slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(product.slug)) {
        throw new Error(`${label} has an unsafe slug.`);
      }
      if (slugs.has(product.slug)) throw new Error(`Duplicate product slug: ${product.slug}.`);
      slugs.add(product.slug);
    } else if (product.type === 'calendario') {
      if (!/^[A-Za-z0-9_-]+$/.test(product.id)) throw new Error(`${label} has an unsafe Amazon product id.`);
    } else {
      throw new Error(`${label} must have a safe slug unless it is a calendar record.`);
    }

    if (product.tags !== undefined && (!Array.isArray(product.tags) || product.tags.some((tag) => typeof tag !== 'string'))) {
      throw new Error(`${label} tags must be an array of strings.`);
    }
    for (const field of ['subtitle', 'heading', 'description', 'categoryLabel', 'priceDisplay', 'imageUrl']) {
      if (product[field] !== undefined && typeof product[field] !== 'string') throw new Error(`${label} has an invalid ${field}.`);
    }
    if (product.imageUrl && !/^https:\/\//i.test(product.imageUrl)) throw new Error(`${label} imageUrl must use HTTPS.`);
    if (product.imageClass !== undefined && !/^[a-z][a-z0-9-]*$/.test(product.imageClass)) {
      throw new Error(`${label} has an invalid imageClass.`);
    }
  }
  return slugs;
}

function productUrl(product) {
  return product.slug
    ? `/productos/${encodeURIComponent(product.slug)}/`
    : `/productos/amazon/?asin=${encodeURIComponent(product.id)}`;
}

function displayPrice(product) {
  return product.priceDisplay || `${new Intl.NumberFormat('es-ES', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(product.price)} €`;
}

function renderDescription(value) {
  return String(value || '').split(/(?:<br\s*\/?\s*>|\r?\n){1,}/i)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => `<p>${escapeHtml(line)}</p>`)
    .join('\n        ');
}

